def preset(battle):
    west, south, east, north = battle['bounds']
    groups = [[i for i, site in enumerate(battle['sites']) if site[4] == side] for side in (0, 1)]
    return dict(id=battle['id'], name=battle['name'], category='historical',
                description=battle['description'],
                regions=[(name, terrain, (lon-west)/(east-west), (north-lat)/(north-south))
                         for name, terrain, lon, lat, side, army in battle['sites']],
                player1_capital=battle['capitals'][0], player2_capital=battle['capitals'][1],
                player1_extra_starts=[i for i in groups[0] if i != battle['capitals'][0]],
                player2_extra_starts=[i for i in groups[1] if i != battle['capitals'][1]],
                battle=battle)


